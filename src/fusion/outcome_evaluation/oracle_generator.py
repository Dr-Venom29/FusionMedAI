"""
FusionMedAI - Outcome-Grounded Synthetic Oracle Cohort Generator
Generates reproducible synthetic multimodal decision packets grounded in a known latent
oracle risk target Y* in [0.0, 1.0], with explicitly controlled errors, uncertainty,
quality degradation, missingness, and uncertainty miscalibration sensitivity scenarios.

METHODOLOGICAL & SIMULATION LIMITATIONS NOTE:
1. In this synthetic simulation, the latent risk target Y* is generated prior to and independently
   of modality observations.
2. In standard scenarios, modality predictive uncertainty is modeled with a component proportional
   to the absolute observation error (|obs_error| * 1.5 + intrinsic_noise). This makes uncertainty
   an informative proxy for hidden observation error under the simulator's generative assumptions.
3. To evaluate robustness when this assumption fails, the generator explicitly includes an
   'UNCERTAINTY_MISCALIBRATION' scenario where uncertainty is decoupled or inverted relative to error.
4. Results generated by this simulator demonstrate mathematical and algorithmic properties under defined
   synthetic generative processes and do not constitute clinical validation on real patient cohorts.
"""

from typing import List, Dict, Any, Optional, Tuple
import numpy as np
import math

from src.fusion.baselines.decision_packet import ModalityRecord
from src.fusion.outcome_evaluation.outcome_packet import OutcomeGroundedPacket, OutcomePacketError
from src.fusion.reliability.global_reliability import (
    FROZEN_RETINA_RELIABILITY,
    FROZEN_FOOT_RELIABILITY,
    FROZEN_CLINICAL_RELIABILITY,
)


class OracleCohortGenerator:
    """
    Independent synthetic cohort generator.
    Produces packets where the true latent risk Y* is defined first,
    followed by causal observation generation across all three modality channels.
    """

    VERSION: str = "1.1.0"

    # Base modality standard errors corresponding to global reliability hierarchy
    MODALITY_SIGMAS: Dict[str, float] = {
        "retina": 0.075,    # High reliability prior (0.929956)
        "foot": 0.095,      # High reliability prior (0.922266)
        "clinical": 0.140,  # Moderate reliability prior (0.825382)
    }

    RELIABILITIES: Dict[str, float] = {
        "retina": FROZEN_RETINA_RELIABILITY,
        "foot": FROZEN_FOOT_RELIABILITY,
        "clinical": FROZEN_CLINICAL_RELIABILITY,
    }

    MODEL_VERSIONS: Dict[str, str] = {
        "retina": "efficientnet_b3_aptos_v1",
        "foot": "efficientnet_b3_adpm_v3.3",
        "clinical": "catboost_hpo_130hosp_v1",
    }

    def __init__(self, seed: int = 115):
        self.seed = int(seed)
        self.rng = np.random.RandomState(self.seed)

    def generate_cohort(
        self,
        n_packets: int = 500,
        cohort_prefix: str = "PKT_OUTCOME",
    ) -> List[OutcomeGroundedPacket]:
        """
        Generates a cohort of n_packets with controlled oracle grounding.
        """
        packets: List[OutcomeGroundedPacket] = []

        for idx in range(n_packets):
            packet_id = f"{cohort_prefix}_{self.seed}_{idx:04d}"
            pkt = self._generate_single_packet(packet_id=packet_id, packet_idx=idx)
            packets.append(pkt)

        return packets

    def _generate_single_packet(
        self, packet_id: str, packet_idx: int
    ) -> OutcomeGroundedPacket:
        # 1. Generate Latent Oracle Risk Y* ~ Beta(2, 2) on [0.02, 0.98]
        raw_target = float(self.rng.beta(2.0, 2.0))
        oracle_risk = round(float(np.clip(raw_target, 0.02, 0.98)), 6)

        # 2. Determine Oracle Tier based on nominal thresholds (0.20, 0.40)
        if oracle_risk < 0.20:
            oracle_tier = "TIER_0_ROUTINE"
        elif oracle_risk < 0.40:
            oracle_tier = "TIER_1_ASSESSMENT"
        else:
            oracle_tier = "TIER_2_ESCALATION"

        # 3. Sample Modality Availability Regime
        # Distribution: 45% Tri-modal (RFC), 35% Dual-modal (RF, RC, FC), 20% Single-modal (R, F, C)
        regime_draw = self.rng.rand()
        if regime_draw < 0.45:
            avail = {"retina": True, "foot": True, "clinical": True}
        elif regime_draw < 0.60:
            avail = {"retina": True, "foot": True, "clinical": False}  # RF
        elif regime_draw < 0.70:
            avail = {"retina": True, "foot": False, "clinical": True}  # RC
        elif regime_draw < 0.80:
            avail = {"retina": False, "foot": True, "clinical": True}  # FC
        elif regime_draw < 0.88:
            avail = {"retina": True, "foot": False, "clinical": False}  # R
        elif regime_draw < 0.94:
            avail = {"retina": False, "foot": True, "clinical": False}  # F
        else:
            avail = {"retina": False, "foot": False, "clinical": True}  # C

        # 4. Determine Packet Scenario
        # 40% Clean, 30% True Degradation, 10% Misleading Quality Unnoticed, 10% False Alarm, 10% Uncertainty Miscalibration
        scenario_draw = self.rng.rand()
        active_mods = [m for m, a in avail.items() if a]

        scenario = "CLEAN"
        degraded_modality = None
        quality_fidelity = "ACCURATE"

        if len(active_mods) > 1:
            if scenario_draw < 0.40:
                scenario = "CLEAN"
            elif scenario_draw < 0.70:
                # True degradation with accurate quality score attenuation
                scenario = self.rng.choice(["MILD_DEGRADATION", "MODERATE_DEGRADATION", "SEVERE_DEGRADATION"])
                degraded_modality = str(self.rng.choice(active_mods))
                quality_fidelity = "ACCURATE"
            elif scenario_draw < 0.80:
                # True degradation but quality sensor fails to detect it (MISLEADING_UNNOTICED)
                scenario = "MODERATE_DEGRADATION"
                degraded_modality = str(self.rng.choice(active_mods))
                quality_fidelity = "MISLEADING_UNNOTICED"
            elif scenario_draw < 0.90:
                # Modality is clean, but quality sensor falsely drops (MISLEADING_FALSE_ALARM)
                scenario = "CLEAN"
                degraded_modality = str(self.rng.choice(active_mods))
                quality_fidelity = "MISLEADING_FALSE_ALARM"
            else:
                # Uncertainty miscalibration: uncertainty is uninformative or inverted relative to error
                scenario = "UNCERTAINTY_MISCALIBRATION"
                degraded_modality = str(self.rng.choice(active_mods))
                quality_fidelity = "UNCERTAINTY_MISCALIBRATED"

        # 5. Generate Modality Observations
        records: Dict[str, ModalityRecord] = {}

        for m in ("retina", "foot", "clinical"):
            if not avail[m]:
                # Inactive Modality (Hard Zeroed)
                records[m] = ModalityRecord(
                    sample_id=f"SAMP_{packet_id}_{m[:3].upper()}",
                    modality=m,
                    risk=0.0,
                    calibrated_probability=(0.0, 0.0),
                    confidence=0.0,
                    uncertainty=0.0,
                    quality=0.0,
                    availability=False,
                    reliability=self.RELIABILITIES[m],
                    model_version=self.MODEL_VERSIONS[m],
                )
                continue

            sigma = self.MODALITY_SIGMAS[m]
            is_degraded = (m == degraded_modality and scenario in ("MILD_DEGRADATION", "MODERATE_DEGRADATION", "SEVERE_DEGRADATION"))
            is_miscalibrated = (m == degraded_modality and scenario == "UNCERTAINTY_MISCALIBRATION")

            # Error generation
            if is_degraded:
                if scenario == "MILD_DEGRADATION":
                    error_shift = float(self.rng.normal(0.12, 0.04))
                    qual_val = float(np.clip(self.rng.uniform(0.50, 0.70), 0.0, 1.0))
                elif scenario == "MODERATE_DEGRADATION":
                    error_shift = float(self.rng.normal(0.22, 0.05))
                    qual_val = float(np.clip(self.rng.uniform(0.30, 0.50), 0.0, 1.0))
                else:  # SEVERE_DEGRADATION
                    error_shift = float(self.rng.normal(0.35, 0.07))
                    qual_val = float(np.clip(self.rng.uniform(0.10, 0.30), 0.0, 1.0))

                # If misleading unnoticed, keep quality artificially high
                if quality_fidelity == "MISLEADING_UNNOTICED":
                    qual_val = float(np.clip(self.rng.uniform(0.85, 0.95), 0.0, 1.0))

                # Bias direction
                sign = 1.0 if self.rng.rand() > 0.4 else -1.0
                obs_error = sign * error_shift + float(self.rng.normal(0, sigma))
            else:
                obs_error = float(self.rng.normal(0, sigma))
                if m == degraded_modality and quality_fidelity == "MISLEADING_FALSE_ALARM":
                    qual_val = float(np.clip(self.rng.uniform(0.20, 0.40), 0.0, 1.0))
                else:
                    qual_val = float(np.clip(self.rng.uniform(0.88, 0.98), 0.0, 1.0))

            # Observed modality risk
            mod_risk = float(np.clip(oracle_risk + obs_error, 0.005, 0.995))

            # Calibrated probabilities
            cal_prob = (round(1.0 - mod_risk, 6), round(mod_risk, 6))

            # Uncertainty Modeling (including Miscalibration sensitivity)
            if is_miscalibrated:
                # 50% High-confidence incorrect (low uncertainty despite large error), 50% Low-confidence correct
                if self.rng.rand() > 0.5:
                    # High confidence incorrect: low uncertainty
                    mod_unc = float(self.rng.uniform(0.01, 0.06))
                    mod_conf = float(self.rng.uniform(0.85, 0.98))
                else:
                    # Low confidence correct: high uncertainty despite small error
                    mod_unc = float(self.rng.uniform(0.65, 0.88))
                    mod_conf = float(self.rng.uniform(0.10, 0.30))
            else:
                # Standard uncertainty correlated with prediction error + intrinsic noise
                intrinsic_u = float(self.rng.uniform(0.01, 0.06))
                mod_unc = float(np.clip(abs(obs_error) * 1.5 + intrinsic_u, 0.001, 0.95))
                extreme_certainty = abs(mod_risk - 0.5) * 2.0
                mod_conf = float(np.clip(0.55 + 0.40 * extreme_certainty - 0.30 * mod_unc + self.rng.normal(0, 0.03), 0.05, 0.99))

            records[m] = ModalityRecord(
                sample_id=f"SAMP_{packet_id}_{m[:3].upper()}",
                modality=m,
                risk=round(mod_risk, 6),
                calibrated_probability=cal_prob,
                confidence=round(mod_conf, 6),
                uncertainty=round(mod_unc, 6),
                quality=round(qual_val, 6),
                availability=True,
                reliability=self.RELIABILITIES[m],
                model_version=self.MODEL_VERSIONS[m],
            )

        return OutcomeGroundedPacket(
            packet_id=packet_id,
            seed=self.seed,
            oracle_risk=oracle_risk,
            oracle_tier=oracle_tier,
            retina=records["retina"],
            foot=records["foot"],
            clinical=records["clinical"],
            scenario=scenario,
            degraded_modality=degraded_modality,
            quality_score_fidelity=quality_fidelity,
        )
